def badge(report: Report) -> str:
    """Generate a local Shields-style SVG badge for a README."""
    color = "#2fbf71" if report.score >= 90 else "#4c8dff" if report.score >= 80 else "#e3a008" if report.score >= 70 else "#e5534b"
    score = f"{report.score}/100"
    # Fixed widths avoid font dependencies while keeping the SVG deterministic.
    left_width, right_width = 92, 72
    total = left_width + right_width
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{total}" height="20" role="img" aria-label="OSS Doctor: {score}">
<title>OSS Doctor: {score}</title>
<linearGradient id="s" x2="0" y2="100%"><stop offset="0" stop-color="#bbb" stop-opacity=".1"/><stop offset="1" stop-opacity=".1"/></linearGradient>
<clipPath id="r"><rect width="{total}" height="20" rx="3" fill="#fff"/></clipPath>
<g clip-path="url(#r)"><rect width="{left_width}" height="20" fill="#24292f"/><rect x="{left_width}" width="{right_width}" height="20" fill="{color}"/><rect width="{total}" height="20" fill="url(#s)"/></g>
<g fill="#fff" text-anchor="middle" font-family="Verdana,Geneva,sans-serif" font-size="11">
<text x="{left_width / 2}" y="14">OSS Doctor</text><text x="{left_width + right_width / 2}" y="14">{score}</text>
</g></svg>
"""


